"""The preview worker on a small media corpus with the real model and the real ffmpeg (plan 03-15).

The evidence for "no speech" and "language not supported" (D-03-11, D-03-12,
D-03-19, D-03-22) on whole files the way the container meets them: each file is
generated by ffmpeg in tmp_path, comes through the content gateway (a
MockTransport in front of the real nc.fetch_media_file), and runs through the
real Preview worker with the real ffprobe, the real ffmpeg and the real engine
child, against a real state.db with a keyed reference and a queued job.

Expected:

- 60 s of silence (WAV), 120 s of pink noise at -25 dBFS (Opus), 60 s of a
  440 Hz sine (MP3): no_speech, no word.
- the German clip as M4A: transcript with the expected word (AVS_TEST_WORD).
- the German clip inside 5 min of silence, starting at 150 s (FLAC): transcript
  with the word at a media time between 150 s and 150 s plus the clip length
  (TRANS-08 across a format and the decode offset).
- the Turkish clip (OGG): unsupported_language and no word in the store
  (D-03-22: much speech by the VAD, no kept word).
- the Spanish clip (WebM): unsupported_language and no word (Parakeet
  transcribes it, the text language drops it).

Needs the pinned models (AVS_TEST_MODELS), the clips of ci/media/fetch_speech.py
(AVS_TEST_SPEECH, AVS_TEST_SPEECH_TR, AVS_TEST_SPEECH_ES, AVS_TEST_WORD), ffmpeg
and ffprobe (AVS_FFMPEG, AVS_FFPROBE or PATH) and 4 GiB of free memory. Without
them it skips with its reason; under CI=true it fails instead. Serial: one
engine child at a time.

The tests read the store with their own SQL, never with the statements of the
implementation.
"""

