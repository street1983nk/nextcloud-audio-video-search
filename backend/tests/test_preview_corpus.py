def _silence(ffmpeg: Path, _encoders: frozenset[str], out_dir: Path) -> Path:
    out = out_dir / "silence.wav"
    run_ffmpeg(ffmpeg, "-f", "lavfi", "-i", "anullsrc=r=44100:cl=mono", "-t", "60", "-c:a", "pcm_s16le", str(out))
    return out


def _noise(ffmpeg: Path, encoders: frozenset[str], out_dir: Path) -> Path:
    codec = pick_encoder(encoders, "libopus", "opus")
    extra = ["-strict", "-2"] if codec == "opus" else []
    out = out_dir / "noise.opus"
    # Amplitude 10^(-25/20) = 0,056: pink noise at about -25 dBFS.
    source = "anoisesrc=color=pink:amplitude=0.056:sample_rate=48000:duration=120"
    run_ffmpeg(ffmpeg, "-f", "lavfi", "-i", source, "-c:a", codec, *extra, "-b:a", "64k", str(out))
    return out


def _sine(ffmpeg: Path, encoders: frozenset[str], out_dir: Path) -> Path:
    codec = pick_encoder(encoders, "libmp3lame")
    out = out_dir / "sine.mp3"
    source = "sine=frequency=440:duration=60:sample_rate=44100"
    run_ffmpeg(ffmpeg, "-f", "lavfi", "-i", source, "-c:a", codec, "-b:a", "128k", str(out))
    return out


