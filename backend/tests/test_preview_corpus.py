# -- one file through the real worker --------------------------------------------------


class Gateway:
    def __init__(self, data: bytes) -> None:
        self.data = data

    def _handler(self, _request: httpx.Request) -> httpx.Response:
        return httpx.Response(200, content=self.data)

    @asynccontextmanager
    async def fetch(
        self, file_id: int, user_id: str, directory: Path, size: int, cap: int
    ) -> AsyncIterator[tuple[nc.FetchResult, Path | None]]:
        async with (
            httpx.AsyncClient(transport=httpx.MockTransport(self._handler)) as client,
            nc.fetch_media_file(file_id, user_id, directory, size, cap, client=client) as kept,
        ):
            yield kept


@dataclass(frozen=True)
class Run:
    outcome: PreviewOutcome
    reason: str | None
    state: str
    words: list[tuple[int, str]]
    all_words: int
    seconds: float


@pytest.fixture(autouse=True)
def models_are_ready() -> Iterator[None]:
    procure.mark_ready(True)
    yield
    procure.mark_ready(False)


def _seed(store: Store, data: bytes) -> int:
    """A keyed reference of one file whose preview job is queued, the way the capture leaves it."""
    store.apply_intake(
        [
            IntakeItem(
                queue_id=1,
                kind="content",
                file_id=FILE_ID,
                storage_id=3,
                etag="e1",
                size=len(data),
                mtime=1_700_000_000,
                prefilter_key=None,
                reader_uid="ana",
                origin="event",
            )
        ]
    )
    claimed = store.next_capture(NOW)
    assert claimed is not None
    media_id = store.mark_keyed(claimed, hashlib.sha256(data).hexdigest(), HEAD, NOW)
    assert media_id is not None
    return media_id


def _read(db: Path, media_id: int) -> tuple[str, list[tuple[int, str]], int]:
    with closing(sqlite3.connect(db)) as conn:
        state = conn.execute("SELECT state FROM preview_job WHERE media_id = ?", (media_id,)).fetchone()[0]
        current = conn.execute(
            "SELECT w.start_ms, w.surface FROM word w JOIN current c ON c.version_id = w.version_id "
            "WHERE c.media_id = ? ORDER BY w.idx",
            (media_id,),
        ).fetchall()
        every = conn.execute(
            "SELECT COUNT(*) FROM word w JOIN transcript t ON t.version_id = w.version_id WHERE t.media_id = ?",
            (media_id,),
        ).fetchone()[0]
    return str(state), [(int(at), str(text)) for at, text in current], int(every)


def _prepare(path: Path, tmp_path: Path) -> tuple[bytes, Path, Path]:
    directory = tmp_path / "tmp" / "preview"
    directory.mkdir(parents=True)
    return path.read_bytes(), tmp_path / "state.db", directory


async def _run(path: Path, tmp_path: Path, models_root: Path, ffmpeg: Path, ffprobe: Path) -> Run:
    data, db, directory = _prepare(path, tmp_path)
    store = Store.open(db)
    try:
        media_id = _seed(store, data)

        async def unread() -> dict[str, str]:
            raise ConnectionError("not needed")

        worker = Preview(
            Services(store=store, index=cast("SearchIndex", None)),
            directory=directory,
            models_root=models_root,
            fetch=Gateway(data).fetch,
            engine_factory=lambda root: EngineWorker(root, headroom=_available_bytes),
            probe=partial(probe_module.probe, ffprobe=ffprobe),
            decode=partial(decode_chunk, ffmpeg=ffmpeg),
            read_settings=unread,
        )
        began = time.perf_counter()
        step = await worker.run_once()
        seconds = time.perf_counter() - began
    finally:
        store.close()
    state, words, every = _read(db, media_id)
    return Run(step.outcome, step.reason, state, words, every, seconds)


@pytest.mark.parametrize("case", CASES, ids=[case.name for case in CASES])
async def test_a_corpus_file_ends_with_its_verdict(
    case: Case,
    tmp_path: Path,
    models_root: Path,
    word: str,
    ffmpeg_bin: Path,
    ffprobe_bin: Path,
    encoders: frozenset[str],
) -> None:
    corpus = tmp_path / "corpus"
    corpus.mkdir()
    path = case.make(ffmpeg_bin, encoders, corpus)

    run = await _run(path, tmp_path, models_root, ffmpeg_bin, ffprobe_bin)

    hits = [at for at, text in run.words if _norm(text) == word]
    # The measurement for the summary (D-03-11): verdict, words, time per file.
    print(
        f"\nCORPUS {case.name}: outcome={run.outcome.value} reason={run.reason} state={run.state} "
        f"words={len(run.words)} stored_words={run.all_words} hits={hits} seconds={run.seconds:.1f}"
    )
    if case.verdict == TRANSCRIPT:
        # Positive control: a German file that is not a transcript means the test itself is broken
        # (no model, no decode, a wrong clip), not that the rule is right.
        assert (run.outcome, run.state) == (PreviewOutcome.COMPLETE, "complete"), (
            f"positive control failed: the German file {case.name} ended {run.outcome.value}/{run.reason}"
        )
        assert hits, "expected word not in the stored transcript"
        if case.make is _german_embedded:
            clip_ms = _clip_ms(_env_path("AVS_TEST_SPEECH"))
            low, high = EMBED_AT_S * 1000, EMBED_AT_S * 1000 + clip_ms
            assert all(low <= at <= high for at in hits), (hits, low, high)
            assert all(low - 1000 <= at <= high + 1000 for at, _ in run.words)
    else:
        assert (run.outcome, run.reason, run.state) == (PreviewOutcome.SKIPPED, case.verdict, "skipped")
        assert run.words == []
        assert run.all_words == 0, "a file without a transcript left words in the store (T-03-53)"
